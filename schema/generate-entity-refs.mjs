#!/usr/bin/env node
/**
 * Generate `entity-refs.json` — the one list of entity-reference fields,
 * read from the normative schema's `x-entity-ref` markers
 * (spec/world.md "Identity"). Name binding, merge rewriting and
 * validation in every reference read this list instead of a
 * hand-written one; each reference embeds a copy and drift-tests it
 * against this file.
 *
 * The schema (`world.schema.json`) is generated from the reference Rust
 * crate and never hand-edited, so the markers live on the Rust fields;
 * this script only reads. Extension schemas (`extensions/*.schema.json`)
 * mark their reference fields the same way, and the list carries them
 * with the path rooted at the extension's namespaced key — an
 * extension field with the core's reference guarantees. Regenerate
 * after a schema change:
 *
 *   node schema/generate-entity-refs.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const schema = JSON.parse(readFileSync(path.join(root, "world.schema.json"), "utf8"));

/** The marked fields, as {scope, path, kind}. `scope` names the object
 *  the path walks from: an entity (or its patch — the same fields), the
 *  manifest's `avatar`, or one creation in `creations[]`. `*` in a path
 *  walks every array element. */
const refs = [];

// Entity-scope markers: WorldEntity and EntityPatch carry the same
// paths (a patch sets the entity's fields), so one scope covers both.
const entityDefs = ["WorldEntity", "EntityPatch"];
const seen = new Set();
for (const def of entityDefs) {
  const properties = schema.$defs?.[def]?.properties ?? {};
  for (const [field, sub] of Object.entries(properties)) {
    const kind = sub?.["x-entity-ref"];
    if (!kind || seen.has(field)) continue;
    seen.add(field);
    refs.push({ scope: "entity", path: [field], kind });
  }
}

// Behavior refs: the behavior kind's marked field, addressed through
// any entity's behaviors array.
for (const variant of schema.$defs?.BehaviorDef?.oneOf ?? []) {
  for (const [kind, body] of Object.entries(variant.properties ?? {})) {
    for (const [field, sub] of Object.entries(body.properties ?? {})) {
      const mark = sub?.["x-entity-ref"];
      if (mark) refs.push({ scope: "entity", path: ["behaviors", "*", kind, field], kind: mark });
    }
  }
}

// Avatar scope.
const avatarRef = schema.$defs?.AvatarDef?.properties?.model_entity?.["x-entity-ref"];
if (avatarRef) refs.push({ scope: "avatar", path: ["model_entity"], kind: avatarRef });

// Creation scope: the marked array's elements.
const creationRef = schema.$defs?.CreationDef?.properties?.entities?.["x-entity-ref"];
if (creationRef) refs.push({ scope: "creation", path: ["entities", "*"], kind: creationRef });

// Extension refs: each extension schema's `EntityBlock` is what an
// entity carries under the extension's namespaced key (the file's
// name, `ext-<name>.schema.json`); its marked fields walk from the
// entity through that key. The walk follows the extension's own
// `$defs` and descends arrays as `*`.
const extensionDir = path.join(root, "extensions");
for (const file of readdirSync(extensionDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const key = file.replace(/\.schema\.json$/, "");
  const ext = JSON.parse(readFileSync(path.join(extensionDir, file), "utf8"));
  const block = ext.$defs?.EntityBlock;
  if (!block) continue;
  const resolve = (node) => {
    const ref = node?.$ref;
    if (typeof ref !== "string") return node;
    const name = ref.replace(/^#\/\$defs\//, "");
    return ext.$defs?.[name] ?? {};
  };
  const walk = (node, trail, depth) => {
    if (!node || depth > 16) return;
    node = resolve(node);
    const mark = node["x-entity-ref"];
    if (mark) {
      refs.push({ scope: "entity", path: [key, ...trail], kind: mark });
      return;
    }
    for (const [field, sub] of Object.entries(node.properties ?? {})) walk(sub, [...trail, field], depth + 1);
    if (node.items) walk(node.items, [...trail, "*"], depth + 1);
  };
  walk(block, [], 0);
}

const order = { entity: 0, avatar: 1, creation: 2 };
refs.sort((a, b) => order[a.scope] - order[b.scope] || a.path.join("/").localeCompare(b.path.join("/")));

const out = {
  comment:
    "The one list of entity-reference fields (spec/world.md \"Identity\"), generated by " +
    "generate-entity-refs.mjs from world.schema.json's x-entity-ref markers — and from the " +
    "extension schemas' (extensions/*.schema.json), their paths rooted at the extension's " +
    "namespaced key — never hand-edited. " +
    "kind: \"bindable\" = a name is accepted at intake and MUST bind to an id at ingestion; " +
    "\"id\" = numeric only. scope: the object the path walks from — an entity (or its patch, the " +
    "same fields), the manifest's avatar, or one creation in creations[]. \"*\" walks every array element.",
  refs,
};
writeFileSync(path.join(root, "entity-refs.json"), `${JSON.stringify(out, null, 2)}\n`);

// The JS reference's embedded copy (the npm package ships only js/src,
// so it can't read the schema at runtime); its drift test compares
// against the canonical file above.
const embed = `// Generated by schema/generate-entity-refs.mjs from schema/entity-refs.json —
// never hand-edited. The one list of entity-reference fields
// (spec/world.md "Identity"); js/test/entity-refs.test.mjs fails when
// this copy drifts from the canonical file.
/** @type {{scope: string, path: string[], kind: "bindable"|"id"}[]} */
export const ENTITY_REFS = ${JSON.stringify(refs, null, 2)};
`;
writeFileSync(path.join(root, "../js/src/entity-refs.mjs"), embed);
console.log(`wrote ${refs.length} entity-reference fields to schema/entity-refs.json and js/src/entity-refs.mjs`);
